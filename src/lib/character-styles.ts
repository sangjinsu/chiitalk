export function getCharacterStyle(id: CharacterId): CharacterStyle { return styles[id]; }

// Select contrastive examples by intent before loose emotion keywords.
function primaryExample(text: string): number {
  if (/싫(?:어(?:[.!…\s]|$)|다|어요|습니다)|거절(?:할|해|하겠)|하지\s?않|안\s?할|원치\s?않|하고\s?싶지\s?않|하지\s?마/.test(text)) return 7;
  if (/고마|감사/.test(text)) return 5;
  if (/무섭|무서|두렵|겁|불안|걱정|긴장/.test(text)) return 2;
  if (/칭찬|해냈|성공|합격|뿌듯|완성/.test(text)) return 4;
  if (/부탁|도와줘(?!서)|도와줄래|들어줄래|돌려줘|해줘|주세요|줄래|원해|먹고\s?싶|갖고\s?싶/.test(text)) return 3;
  if (/피곤|쉬|지쳤|지쳐|졸|휴식|힘들/.test(text)) return 6;
  if (/속상|슬프|슬퍼|실수|울고|미안|서운/.test(text)) return 1;
  if (/기쁘|기뻐|행복|좋아|좋다|신나|잘\s?풀|축하/.test(text)) return 0;
  return 0;
}

const contrasts = [[1, 7], [0, 7], [0, 7], [7, 5], [0, 1], [3, 7], [2, 7], [3, 0]] as const;
export function selectCharacterExamples(id: CharacterId, text: string, limit = 3): readonly CharacterExample[] {
  const all = getCharacterStyle(id).examples;
  const primary = primaryExample(text);
  const order = [primary, ...contrasts[primary]!, 0, 1, 2, 3, 4, 5, 6, 7];
  return [...new Set(order)].slice(0, Math.max(0, Math.min(3, Math.floor(limit)))).map((index) => all[index]!);
}
