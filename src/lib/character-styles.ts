export function getCharacterStyle(id: CharacterId): CharacterStyle { return styles[id]; }

const emotionPatterns = [
  /기쁘|기뻐|행복|좋아|좋다|신나|잘 풀|축하/,
  /속상|슬프|슬퍼|실수|울|미안|걱정|다시/,
  /무섭|무서|두렵|겁|위험|소리/,
  /먹|간식|맛|배고|갖고|원해/,
  /해냈|칭찬|성공|합격|완성/,
  /고마|감사|도와|친구|함께/,
  /피곤|쉬|지쳤|지쳐|졸|휴식/,
  /싫|거절|하지 않|안 할|못 해|아니/,
] as const;

export function selectCharacterExamples(id: CharacterId, text: string, limit = 3): readonly CharacterExample[] {
  const all = getCharacterStyle(id).examples;
  const primary = emotionPatterns.findIndex((pattern) => pattern.test(text));
  const order = primary < 0 ? [0, 1, 7, 2, 3, 4, 5, 6] : [primary, (primary + 1) % 8, (primary + 4) % 8, 0, 1, 2, 3, 4, 5, 6, 7];
  return [...new Set(order)].slice(0, Math.max(0, Math.min(3, Math.floor(limit)))).map((index) => all[index]!);
}
